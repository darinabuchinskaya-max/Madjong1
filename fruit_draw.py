def _px(surface, color, cx, cy, size, grid_x, grid_y):
    ps = max(1, size // 8)
    ox = cx - 4 * ps
    oy = cy - 4 * ps
    pygame.draw.rect(surface, color, (ox + grid_x * ps, oy + grid_y * ps, ps, ps))


def _grid(surface, cx, cy, size, pixels):
    ps = max(1, size // 8)
    ox = cx - 4 * ps
    oy = cy - 4 * ps
    for (gx, gy, color) in pixels:
        pygame.draw.rect(surface, color, (ox + gx * ps, oy + gy * ps, ps, ps))


